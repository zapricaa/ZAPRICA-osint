"""Synthetic Demo Collector Adapter: Provides simulated fixture data for testing only."""

import time
from datetime import datetime, timezone
from typing import Dict, Any, Tuple, Set, Optional, List
from fastapi import HTTPException

from app.collection.adapters.base import BaseCollectorAdapter
from app.collection.contracts import CollectorType, TargetType, CollectorStatus, RawCollectorOutput
from app.collection.schemas import DemoResult


class SyntheticDemoCollectorAdapter(BaseCollectorAdapter):
    """Synthetic Demo Collector for tests and air-gapped demonstrations."""

    @property
    def tool_id(self) -> str:
        return "demo_collector"

    @property
    def name(self) -> str:
        return "Synthetic Demo Intelligence Collector"

    @property
    def description(self) -> str:
        return "Returns deterministic synthetic fixtures for reserved test identifiers (*@demo.example, demo_*, demo.example). Never accesses real networks."

    @property
    def collector_type(self) -> CollectorType:
        return CollectorType.SYNTHETIC

    @property
    def supported_target_types(self) -> Set[TargetType]:
        return {TargetType.DOMAIN, TargetType.EMAIL, TargetType.USERNAME}

    def is_available(self) -> Tuple[bool, str]:
        return True, "Synthetic fixture adapter is always ready"

    def is_reserved_demo_target(self, target: str, target_type: TargetType) -> bool:
        t = target.strip().lower()
        if target_type == TargetType.EMAIL:
            return t.endswith("@demo.example")
        if target_type == TargetType.USERNAME:
            return t.startswith("demo_")
        if target_type == TargetType.DOMAIN:
            return t == "demo.example" or t.endswith(".demo.example")
        return False

    def validate_target(self, target: str) -> None:
        if not target.strip():
            raise HTTPException(status_code=400, detail="Target identifier cannot be empty.")

    async def execute(
        self,
        target: str,
        options: Optional[Dict[str, Any]] = None,
        task_id: Optional[str] = None,
    ) -> RawCollectorOutput:
        self.validate_target(target)
        t = target.strip().lower()

        # Determine target type
        if "@" in t:
            target_type = TargetType.EMAIL
        elif "." in t and not t.startswith("demo_"):
            target_type = TargetType.DOMAIN
        else:
            target_type = TargetType.USERNAME

        start_time = time.monotonic()
        findings: List[Dict[str, Any]] = []
        warnings: List[str] = ["SYNTHETIC DATA: This finding was generated by a demo collector and does not represent real intelligence."]

        if not self.is_reserved_demo_target(t, target_type):
            # Non-demo target: strictly return empty findings to prevent accidental fake reports on real entities
            warnings.append(f"Target '{target}' is not a reserved demo identifier. Demo collector returned empty set.")
        else:
            if target_type == TargetType.EMAIL:
                local_part = t.split("@")[0]
                uname = "demo_" + local_part
                findings = [
                    {
                        "source": "synthetic:breach",
                        "finding_type": "credential_leak",
                        "title": "Synthetic Breach: DemoStore (2020-05)",
                        "value": "DemoStore (2020-05)",
                        "data_classes": ["Email addresses", "Passwords"],
                        "confidence_level": "medium",
                        "is_synthetic": True,
                    },
                    {
                        "source": "synthetic:account",
                        "finding_type": "contact",
                        "title": "Synthetic Account Registration",
                        "value": "demo-portal.example",
                        "username_handle": uname,
                        "confidence_level": "low",
                        "is_synthetic": True,
                    },
                ]

            elif target_type == TargetType.USERNAME:
                findings = [
                    {
                        "source": "synthetic:sherlock",
                        "finding_type": "profile",
                        "title": "Candidate Profile on DemoHub",
                        "value": f"https://demohub.example/{t}",
                        "confidence_level": "low",
                        "is_synthetic": True,
                    },
                    {
                        "source": "synthetic:sherlock",
                        "finding_type": "profile",
                        "title": "Candidate Profile on DemoCode",
                        "value": f"https://democode.example/{t}",
                        "confidence_level": "low",
                        "is_synthetic": True,
                    },
                ]

            elif target_type == TargetType.DOMAIN:
                findings = [
                    {
                        "source": "synthetic:whois",
                        "finding_type": "domain_info",
                        "title": "WHOIS Registration: Synthetic Registrar Ltd",
                        "value": "Registrar: Synthetic Registrar Ltd (Created: 2018-01-15)",
                        "confidence_level": "high",
                        "is_synthetic": True,
                    },
                    {
                        "source": "synthetic:dns",
                        "finding_type": "network_intel",
                        "title": "DNS Record: A 192.0.2.100",
                        "value": "A 192.0.2.100",
                        "confidence_level": "high",
                        "is_synthetic": True,
                    },
                    {
                        "source": "synthetic:theharvester",
                        "finding_type": "domain_info",
                        "title": "Subdomain: mail.demo.example",
                        "value": f"mail.{t}",
                        "confidence_level": "medium",
                        "is_synthetic": True,
                    },
                ]

        duration_ms = int((time.monotonic() - start_time) * 1000)
        demo_result = DemoResult(
            identifier=target,
            target_type=target_type.value,
            is_synthetic=True,
            findings=findings,
        )

        import json
        raw_text = json.dumps(demo_result.model_dump(), indent=2)
        raw_bytes = raw_text.encode("utf-8")

        return RawCollectorOutput(
            tool_id=self.tool_id,
            tool_version="1.0.0",
            status=CollectorStatus.SUCCESS,
            target=target,
            target_type=target_type,
            raw_bytes=raw_bytes,
            stdout=raw_text,
            stderr="",
            exit_code=0,
            execution_duration_ms=duration_ms,
            warnings=warnings,
            errors=[],
            parsed_data=demo_result.model_dump(),
            is_synthetic=True,
            collected_at=datetime.now(timezone.utc),
        )

