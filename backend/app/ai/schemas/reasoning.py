"""Structured Pydantic Schemas for AI Brain Reasoning."""

from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class InvestigationObjectiveAnalysis(BaseModel):
    """Structured analysis of an incoming investigation request."""

    target_type: Literal["domain", "ip", "username", "organization", "person", "email", "general"] = Field(
        ..., description="Detected primary OSINT entity type"
    )
    primary_identifier: str = Field(
        ..., description="Extracted target identifier (e.g. example.com, user123)"
    )
    scope_compliance_verified: bool = Field(
        ..., description="Whether the extracted target conforms to approved investigation constraints"
    )
    identified_objectives: List[str] = Field(
        default_factory=list, description="Granular intelligence objectives to achieve"
    )
    risk_assessment: str = Field(
        ..., description="Assessment of active touch, OPSEC, and rate limit risks"
    )


class PlannedTaskSchema(BaseModel):
    """Single decomposed investigation task planned by Main Head."""

    title: str = Field(..., description="Short task title")
    description: str = Field(..., description="Detailed instructions for the assigned sub-head agent")
    assigned_agent: Literal["browser_head", "terminal_head"] = Field(
        ..., description="Designated sub-head agent responsible for execution"
    )
    priority: int = Field(default=3, ge=1, le=5, description="Priority from 1 (highest) to 5 (lowest)")
    suggested_tools: List[str] = Field(
        default_factory=list, description="Approved tool identifiers suitable for this task"
    )
    required_inputs: Dict[str, Any] = Field(
        default_factory=dict, description="Validated inputs and parameters for the task"
    )


class InvestigationPlanSchema(BaseModel):
    """Full structured plan generated by Main Head for an investigation."""

    summary: str = Field(..., description="High-level summary of the investigation approach")
    tasks: List[PlannedTaskSchema] = Field(
        ..., min_length=1, description="List of decomposed tasks to execute"
    )
    rationale: str = Field(..., description="Reasoning behind task sequencing and agent selection")


class BrowserTaskDecompositionSchema(BaseModel):
    """Sub-task plan generated by Browser Head for its browser workers."""

    worker_type: Literal[
        "web_research",
        "profile_research",
        "website_intel",
        "content_extraction",
        "data_cleaning",
        "duplicate_removal",
        "data_classification",
        "data_structuring",
    ] = Field(..., description="Designated browser worker or data processor")
    action: str = Field(..., description="Action to perform (e.g., search, scrape, inspect)")
    target_url_or_query: str = Field(..., description="Target URL or query string")
    expected_data_type: str = Field(..., description="Expected extracted format (e.g. metadata, links, text)")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Worker parameters")


class TerminalTaskDecompositionSchema(BaseModel):
    """Sub-task plan generated by Terminal Head for its terminal workers."""

    worker_type: Literal[
        "cli_osint",
        "network_intel",
        "metadata_analysis",
        "file_processing",
        "data_cleaning",
        "data_normalization",
        "duplicate_detection",
        "data_indexing",
    ] = Field(..., description="Designated terminal worker or data processor")
    tool_name: str = Field(..., description="Approved TIMS tool identifier")
    tool_parameters: Dict[str, Any] = Field(default_factory=dict, description="Validated tool parameters")
    rationale: str = Field(..., description="Reason for using this CLI tool")


class ProposedToolCall(BaseModel):
    """Tool invocation proposal generated by LLM reasoning."""

    tool_name: str = Field(..., description="Name of the tool to invoke")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Arguments to pass to the tool")
    justification: str = Field(..., description="Explanation of why this tool call is necessary")


class FindingsAnalysisSchema(BaseModel):
    """Structured correlation and synthesis of collected findings."""

    observed_facts: List[str] = Field(
        default_factory=list, description="Directly observed, verifiable facts with artifact provenance"
    )
    hypotheses_and_inferences: List[str] = Field(
        default_factory=list, description="Analytical hypotheses, correlations, and educated inferences"
    )
    identified_conflicts: List[Dict[str, str]] = Field(
        default_factory=list,
        description="Conflicts between sources (e.g. conflicting registrant name between WHOIS and web page)",
    )
    identified_gaps: List[str] = Field(
        default_factory=list, description="Missing intelligence points requiring follow-up"
    )
    confidence_score: float = Field(
        default=0.8, ge=0.0, le=1.0, description="Aggregate confidence rating (0.0 to 1.0)"
    )


class FollowUpDecisionSchema(BaseModel):
    """Decision by Main Head on whether to terminate or issue follow-up tasks."""

    investigation_complete: bool = Field(
        ..., description="True if investigation objectives are met or budget exhausted"
    )
    completion_reason: str = Field(
        ..., description="Explanation of why the investigation is finished or continuing"
    )
    follow_up_tasks: List[PlannedTaskSchema] = Field(
        default_factory=list, description="Follow-up tasks if investigation is not complete"
    )


class ExecutiveSummarySchema(BaseModel):
    """Final investigation report executive synthesis."""

    title: str = Field(..., description="Formal investigation title")
    key_findings: List[str] = Field(
        ..., min_length=1, description="Primary takeaways and identified intelligence"
    )
    threat_level: Literal["info", "low", "medium", "high", "critical"] = Field(
        default="info", description="Overall risk / threat level assessment"
    )
    evidence_summary: str = Field(
        ..., description="Summary of evidence artifacts gathered and provenance verification"
    )
    recommended_actions: List[str] = Field(
        default_factory=list, description="Suggested next investigative or operational steps"
    )
